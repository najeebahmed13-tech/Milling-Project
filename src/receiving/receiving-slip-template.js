function normalizeField(field, fallback) {
  const configuredOrder = Number(field?.order);
  return {
    ...fallback,
    ...field,
    visible: field?.visible !== false,
    label: field?.label || fallback.label,
    order: Number.isFinite(configuredOrder) ? configuredOrder : fallback.order,
  };
}

export function resolveReceivingSlipTemplate(template = DEFAULT_RECEIVING_SLIP_TEMPLATE) {
  const source = template || DEFAULT_RECEIVING_SLIP_TEMPLATE;
  const sourceSections = Array.isArray(source.sections) ? source.sections : [];
  const sections = DEFAULT_RECEIVING_SLIP_TEMPLATE.sections.map((defaultSection) => {
    const configuredSection = sourceSections.find((section) => section.key === defaultSection.key);
    const configuredFields = Array.isArray(configuredSection?.fields) ? configuredSection.fields : [];
    const normalizedSection = {
      ...defaultSection,
      ...configuredSection,
      visible: configuredSection?.visible !== false,
      fields: defaultSection.fields.map((defaultField) => normalizeField(
        configuredFields.find((field) => field.key === defaultField.key),
        defaultField,
      )).sort((left, right) => left.order - right.order),
    };
    const configuredOrder = Number(configuredSection?.order);
    normalizedSection.order = Number.isFinite(configuredOrder) ? configuredOrder : defaultSection.order;
    return normalizedSection;
  }).sort((left, right) => left.order - right.order);

  return {
    ...DEFAULT_RECEIVING_SLIP_TEMPLATE,
    ...source,
    version: Number(source.version) || RECEIVING_SLIP_TEMPLATE_VERSION,
    header: { ...DEFAULT_RECEIVING_SLIP_TEMPLATE.header, ...(source.header || {}) },
    sections,
    formatting: { ...DEFAULT_RECEIVING_SLIP_TEMPLATE.formatting, ...(source.formatting || {}) },
    print: { ...DEFAULT_RECEIVING_SLIP_TEMPLATE.print, ...(source.print || {}) },
  };
}

export function getReceivingSlipSection(template, key) {
  return template.sections.find((section) => section.key === key);
}

export function getReceivingSlipField(section, key) {
  return section?.fields.find((field) => field.key === key);
}
